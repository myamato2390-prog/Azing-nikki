// 潮位（cm、潮位表の基準面から）。ms は世界時のミリ秒
// 気象庁の潮位表と見比べて決めた時刻の合わせ（分）。これで1時間ごとの潮位のずれが平均2cm以下になる
const SHIFT_MIN = 9.5;
export function tideHeight(station, ms) {
  const st = STATIONS[station];
  const { args, N } = astro(ms - SHIFT_MIN * 60000);
  const nf = nodal(N);
  let h = st.msl;
  for (const [name, amp, kappa] of st.consts) {
    const [dd, off, fam] = D[name];
    let f = 1, u = 0;
    for (const [k, n] of Object.entries(fam)) { f *= Math.pow(nf[k][0], Math.abs(n)); u += n * nf[k][1]; }
    const V = dd.reduce((a, k, i) => a + k * args[i], 0) + off;
    h += f * amp * Math.cos(rad(V + u - kappa));
  }
  return h;
}

// 日本時間の 'YYYY-MM-DD' と 時（小数可、24以上は翌日） → 世界時のミリ秒
export function jstToMs(date, hours) {
  const [y, m, d] = date.split('-').map(Number);
  return Date.UTC(y, m - 1, d) + (hours - 9) * 3600000;
}

// 満潮・干潮を探す。date の fromH 時〜toH 時（24以上は翌日）。6分ごとに調べて、山と谷を1分単位で詰める
// → [{ type: 'high'|'low', h: 当日0時からの時間, cm }]
export function tideEvents(station, date, fromH = 0, toH = 24) {
  const at = (hh) => tideHeight(station, jstToMs(date, hh));
  const step = 0.1;
  const out = [];
  let prev = at(fromH - step), cur = at(fromH);
  for (let hh = fromH; hh < toH; hh += step) {
    const next = at(hh + step);
    const isHigh = cur > prev && cur >= next, isLow = cur < prev && cur <= next;
    if (isHigh || isLow) {
      // 前後1分刻みで一番高い（低い）ところ
      let best = hh, bv = cur;
      for (let k = -6; k <= 6; k++) {
        const t = hh + k / 60, v = at(t);
        if (isHigh ? v > bv : v < bv) { best = t; bv = v; }
      }
      if (best >= fromH && best < toH) out.push({ type: isHigh ? 'high' : 'low', h: best, cm: Math.round(bv) });
    }
    prev = cur; cur = next;
  }
  return out;
}

const hm = (hours) => {
  const m = Math.round(hours * 60);
  const mm = ((m % 1440) + 1440) % 1440;
  return `${String(Math.floor(mm / 60)).padStart(2, '0')}:${String(mm % 60).padStart(2, '0')}`;
};

// 釣行の満潮・干潮（めやす）。夕方以降に始める釣行（開始が12時以降・未入力）は当日12時〜翌日12時、
// 朝からの釣行は当日0〜24時。offsetMin は港ごとの補正（分）
// → { highs: [{ time, cm, nextDay }], lows: [...], station: '松山' }
export function tideForTrip(side, date, startTime = '', offsetMin = 0) {
  const station = SIDE_STATION[side];
  if (!station || !/^\d{4}-\d{2}-\d{2}$/.test(date || '')) return null;
  const night = !startTime || startTime >= '12:00';
  const [from, to] = night ? [12, 36] : [0, 24];
  const off = (Number(offsetMin) || 0) / 60;
  const ev = tideEvents(station, date, from - off, to - off).map((e) => ({ ...e, h: e.h + off }));
  const conv = (e) => ({ time: hm(e.h), cm: e.cm, nextDay: e.h >= 24 });
  return {
    highs: ev.filter((e) => e.type === 'high').map(conv),
    lows: ev.filter((e) => e.type === 'low').map(conv),
    station: STATIONS[station].name,
  };
}
